export function getWordList(difficulty: 'easy' | 'medium' | 'hard' | 'expert'): string[] {
  switch (difficulty) {
    case 'easy': return EASY_WORDS
    case 'medium': return MEDIUM_WORDS
    case 'hard': return HARD_WORDS
    case 'expert': return HARD_WORDS
  }
}

export function generateWords(count: number, difficulty: 'easy' | 'medium' | 'hard' | 'expert'): string {
  const wordList = getWordList(difficulty)
  const words: string[] = []
  for (let i = 0; i < count; i++) {
    words.push(wordList[Math.floor(Math.random() * wordList.length)])
  }

  if (difficulty === 'expert') {
    return words.map((w, i) => {
      if (i > 0 && Math.random() < 0.15) w = w.charAt(0).toUpperCase() + w.slice(1)
      if (Math.random() < 0.1) w += ['!', '?', '.', ',', ';', ':'][Math.floor(Math.random() * 6)]
      if (Math.random() < 0.05) w = `"${w}"`
      return w
    }).join(' ')
  }

  if (difficulty === 'hard') {
    return words.map(w => {
      if (Math.random() < 0.1) w += ['.', ',', '!', '?'][Math.floor(Math.random() * 4)]
      return w
    }).join(' ')
  }

  return words.join(' ')
}
